#!/usr/bin/env python3
"""Render bench/optimizations/cat_repack/RESULTS.md from the two stage-11 evidence files.

Inputs (unchanged, committed): launch_evidence/cat_repack.json (call 1) and
launch_evidence/cat_validation.json (call 2). Every number in the output is read
from those files; nothing is re-measured or hand-entered.

    python3 scripts/cat_results_table.py            # write RESULTS.md
    python3 scripts/cat_results_table.py --check    # exit 1 if RESULTS.md is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
EV = REPO / "bench/tritonbench_g/add_example/launch_evidence"
OUT = REPO / "bench/optimizations/cat_repack/RESULTS.md"
COLS = ["eager", "compiled_dynamic", "fallback_equiv", "compiled_static", "cand_A_tiled", "cand_B_fastdiv"]
SHORT = {"eager": "eager", "compiled_dynamic": "dyn", "fallback_equiv": "fallback", "compiled_static": "static",
         "cand_A_tiled": "A", "cand_B_fastdiv": "B"}
VALID = ("eager", "compiled_dynamic", "fallback_equiv")  # valid for changing shapes without recompiling


def f(x, nd=3):
    return "—" if x is None else f"{x:.{nd}f}"


def shape(r):
    return f"{r['n']} × {r['wset']} {tuple(r['widths'])}"


def metric_table(rows, metric, nd, unit):
    head = "| shape | " + " | ".join(SHORT[c] for c in COLS) + " | B / best valid | B / static | bitwise (all 6) |"
    out = [f"**{metric}** ({unit})", "", head, "|" + "---|" * (len(COLS) + 4)]
    for r in rows:
        if "summary" not in r:
            last = str(r.get('error', '')).strip().splitlines()[-1][:80]
            out.append(f"| (shape process failed) | `{last}` |" + " |" * (len(COLS) + 3))
            continue
        get = (lambda c: r["kernel_us"][c]["median"]) if metric == "kernel_us" else \
            (lambda c: r["summary"][metric][c])
        best = min(get(c) for c in VALID)
        bit = all(r["bitwise_equal_eager"].values())
        out.append(f"| {shape(r)} | " + " | ".join(f(get(c), nd) for c in COLS)
                   + f" | {best / get('cand_B_fastdiv'):.2f}× | {get('compiled_static') / get('cand_B_fastdiv'):.2f}× "
                   f"| {'yes' if bit else 'NO'} |")
    return out


def render() -> str:
    c1 = json.loads((EV / "cat_repack.json").read_text())
    c2 = json.loads((EV / "cat_validation.json").read_text())
    L = ["# Stage 11 results: every measured shape", "",
         "Generated by `scripts/cat_results_table.py` from `launch_evidence/cat_repack.json` (call 1) and",
         "`launch_evidence/cat_validation.json` (call 2). Do not edit by hand.", "",
         f"Host: {c2['gpu_name']} (Modal; CPU model not reported, "
         f"nproc = {c2['cpu'].split()[-1]}), torch {c2['torch']}, Triton {c2['triton']}, bfloat16.",
         "One subprocess per shape. Three rotated trials; each number is the median of the three trial medians.",
         "",
         "Columns:",
         "- **eager**: the issue's program in eager mode.",
         "- **dyn**: `torch.compile(dynamic=True)` with `mark_dynamic` on the last dimension.",
         "- **fallback**: our emulation of an ATen-cat fallback: compiled adds, then eager `torch.cat` twice.",
         "- **static**: `torch.compile(dynamic=False)`, which recompiles for every shape.",
         "- **A**: the tiled candidate with runtime division.",
         "- **B**: the fast-division candidate (stage 11, proved).",
         "",
         "Ratio columns:",
         "- **B / best valid** compares B with the fastest of eager, dyn and fallback at that shape. These are the",
         "  baselines that need no recompilation per shape.",
         "- **B / static** above 1 means B is faster.",
         "",
         "Metrics:",
         "- `issue_ms`: CUDA-event time per call over 100 back-to-back calls, after 25 warm-up calls.",
         "- `single_us`: host wall time of one call plus synchronize (median of 100).",
         "- `kernel_us`: summed device time of the call's kernels (torch.profiler, median of 10 calls).",
         "- All timings are warm-cache: the L2 is not flushed between calls.", "",
         "Two discrepancies these files do not explain:",
         "- **Host-bound small shapes.** Where `issue_ms` is well above `kernel_us` for static, A and B at small",
         "  shapes, the back-to-back rate is limited by per-call host time rather than by the device.",
         "- **dyn at large shapes.** Only dyn has `issue_ms` above `kernel_us` at large shapes: up to 1.6× (5.51 ms",
         "  against 3.52 ms at 32768 × issue). That gap is too large to be host time. The other five columns agree",
         "  within about 10%. The stage-12 harness records device time in several ways so the cause can be",
         "  isolated.",
         "",
         "## Call 2: validation sequence (10 shapes)", ""]
    for m, nd, u in (("issue_ms", 3, "ms/call"), ("kernel_us", 1, "µs device"), ("single_us", 1, "µs host")):
        L += metric_table(c2["rows"], m, nd, u) + [""]
    L += ["## Call 2: held-out shapes (4, chosen before call 2)", ""]
    for m, nd, u in (("issue_ms", 3, "ms/call"), ("kernel_us", 1, "µs device"), ("single_us", 1, "µs host")):
        L += metric_table(c2["held_out_rows"], m, nd, u) + [""]
    L += ["## Call 2: compile / first-call cost (s, per shape process)", "",
          "| shape | " + " | ".join(SHORT[c] for c in COLS[1:]) + " |", "|" + "---|" * len(COLS)]
    for r in c2["rows"] + c2["held_out_rows"]:
        if "compile_s" in r:
            L.append(f"| {shape(r)} | " + " | ".join(f(r['compile_s'].get(c), 2) for c in COLS[1:]) + " |")
    L += ["", "## Call 2: one-process cold sequence (first call of each shape, s)", "",
          "| shape | dyn | A | B | eager |", "|---|---|---|---|---|"]
    for r in c2["cold_sequence"]["first_call_s"]:
        L.append(f"| {r['n']} × {r['wset']} | {f(r['compiled_dynamic'], 4)} | {f(r['cand_A_tiled'], 4)} | "
                 f"{f(r['cand_B_fastdiv'], 4)} | {f(r['eager'], 4)} |")
    cs = c2["cold_sequence"]
    L += ["", f"Triton compiled variants over the sequence: {cs['triton_compiled_variants']}. "
          f"Dynamo counters: {cs['dynamo_counters']}.", "",
          "## Call 2: edge cases (correctness only)", "", "| n × widths | n·W | A | B |", "|---|---|---|---|"]
    for r in c2["edge_rows"]:
        L.append(f"| {r['n']} × {r['wset']} | {r['nW']} | {r['cand_A_tiled']} | {r['cand_B_fastdiv']} |")
    L += ["", "## Call 1: reproduction sequence (10 shapes)", ""]
    L += metric_table(c1["rows"], "issue_ms", 3, "ms/call") + [""]
    rp = c1["reproduce"]
    L += ["Notes on call 1:",
          f"- **Reproduction criterion.** Declared before call 1: dyn at least 1.3× slower than eager, with `% ks` or",
          "  `// ks` in the generated code, at 6 or more of 10 shapes.",
          f"  Result: {rp['reproducing']} of {rp['shapes']} shapes reproduced, so `reproduced = {rp['reproduced']}`.",
          "- **Cold sequence failed** in call 1. B crashed at a power-of-two width: Triton specialized the integer",
          "  argument `magic == 1` to a constant, so it had no `.to` method. Fixed before call 2 with",
          "  `do_not_specialize` and a guard before allocation.",
          "  The error text is kept in `cat_repack.json` under `cold_sequence.error`.",
          "- **Three shape processes failed** in call 1 with the same crash: the three `mid` shapes, where",
          "  W = 8192 is a power of two.",
          "- **The call-2 cold sequence** shows one extra B compile, 0.33 s at 2048 × llama8b (W = 12288), for a",
          "  variant count of 2. The specialization key that changed was not recorded.", ""]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
